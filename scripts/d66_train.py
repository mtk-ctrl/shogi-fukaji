"""D66: train current D64 directly after 1000 new games; replay old train without audits."""
from pathlib import Path
import argparse,json,random,tarfile,sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from fukaji.online_learning import atomic_json,digest,load_snapshot,validate_game,make_samples,fit,save_snapshot,game_key
from scripts import d66_games as games
from scripts import d41_public_20 as archive_tool

BASE=games.BASE
SEED=games.SEED+77
def read_member(t,name):
    return t.extractfile(name).read()

def train(state,parent_file,old_file,source_file,source_sha,out):
    for p,sha in ((state,games.STATE_SHA),(parent_file,games.D64_TRAIN_SHA),
                  (old_file,games.D64_SELFPLAY_SHA),(source_file,source_sha)):
        games.checksum(p,sha)
    formal=json.loads(Path("formal/model.json").read_text())
    if formal["research_snapshot_sha256"]!=BASE or formal["optimizer_step"]!=10974 or formal.get("search_backend_variant")!="d48_pvs_mate":
        raise ValueError("D64 is no longer current; refuse to train")
    out.mkdir(parents=True,exist_ok=True)
    model_dir=out/"models";model_dir.mkdir(exist_ok=True)
    with tarfile.open(state,"r:gz") as t:
        meta=json.load(t.extractfile("d17-state/state.json"))
        bootstrap=read_member(t,"d17-state/bootstrap-train.jsonl")
    if digest(bootstrap)!=meta["bootstrap"]["sha256"]:
        raise ValueError("bootstrap SHA mismatch")
    with tarfile.open(parent_file,"r:gz") as t:
        report=json.load(t.extractfile("report.json"))
        if (report["schema"]!="d64-learned1000-v1" or
            report["baseline"]!="e04e85dfebb507131df591bf0206e27771afe6944f3249124dfaf6eab5de51fb" or
            report["trained_sha256"]!=BASE or report["optimizer_step_after"]!=10974 or
            report["source_sha256"]!=games.D64_SELFPLAY_SHA):
            raise ValueError("D64 trained source not approved")
        for ext in ("npz","json"):
            (model_dir/f"{BASE}.{ext}").write_bytes(read_member(t,f"{BASE}.{ext}"))
    parent,opt,_=load_snapshot(model_dir,BASE)
    if opt is None or opt["step"]!=10974:raise ValueError("Adam10974 missing")
    with tarfile.open(source_file,"r:gz") as t:
        plan=json.load(t.extractfile("plan.json"));report=json.load(t.extractfile("report.json"))
        names=sorted(n for n in t.getnames() if n.startswith("games/game-") and n.endswith(".json"))
        if (plan["schema"]!="d66-d64-1000-v1" or report["schema"]!="d66-selfplay1000-result-v1" or
            report["model"]!=BASE or report["games"]!=1000 or len(names)!=1000):
            raise ValueError("1000-game D64 provenance mismatch")
        if report["plan_sha256"]!=digest((json.dumps(plan,indent=2,ensure_ascii=False,allow_nan=False)+"\n").encode()):
            raise ValueError("D45 plan changed")
        fresh=[json.load(t.extractfile(n)) for n in names]
    protected=set(meta["protected_parents"])
    parents=set();keys=set()
    for i,g in enumerate(fresh):
        if (g["game_index"]!=i or g["parent_id"]!=plan["families"][i]["parent_id"] or
            g["role"]!="train" or g["models"]!=[BASE,BASE] or
            g["moves"][:6]!=plan["families"][i]["prefix"]):
            raise ValueError("D58 selfplay game differs from frozen plan")
        validate_game(g,parent,training=True,protected=protected)
        if g["parent_id"] in parents or game_key(g) in keys:
            raise ValueError("duplicate D58 train experience")
        parents.add(g["parent_id"]);keys.add(game_key(g))
    resolved=[g for g in fresh if g["status"] in ("checkmate","perpetual_check","repetition_draw")]
    if len(resolved)<800:raise ValueError("too few resolved new training games")
    if plan.get("search_variant")!="d48_pvs_mate" or report.get("formal_search_variant")!="d48_pvs_mate":
        raise ValueError("new D58 train must be generated by PVS+mate official search")
    old_boot=[json.loads(x) for x in bootstrap.splitlines() if x.strip()]
    if len(old_boot)!=665:raise ValueError("bootstrap train not 665 games")
    for g in old_boot:validate_game(g,parent,training=True,protected=protected)
    with tarfile.open(old_file,"r:gz") as t:
        old_plan=json.load(t.extractfile("plan.json"))
        old_report=json.load(t.extractfile("report.json"))
        old_names=sorted(n for n in t.getnames() if n.startswith("games/game-") and n.endswith(".json"))
        if (old_plan["schema"]!="d64-d62-1000-v1" or old_report["schema"]!="d64-selfplay1000-result-v1" or
            old_report["games"]!=1000 or len(old_names)!=1000):
            raise ValueError("D52 prior training source is not verified")
        previous=[json.load(t.extractfile(n)) for n in old_names]
    prev_parents=set();prev_resolved=[]
    for g in previous:
        validate_game(g,parent,training=True,protected=protected)
        if g["parent_id"] in prev_parents:raise ValueError("duplicate first-round parent")
        prev_parents.add(g["parent_id"])
        if g["status"] in ("checkmate","perpetual_check","repetition_draw"):prev_resolved.append(g)
    if len(prev_resolved)<800 or parents&prev_parents:
        raise ValueError("first and second round train parents overlap or not enough resolved")
    replay=random.Random(SEED+19).sample(prev_resolved,300)
    inputs,targets,sample_stats=make_samples(resolved+old_boot+replay,parent,seed=SEED,
        per_game=32,outcome_weight=.75,td_lambda=.8,protected=protected)
    candidate,opt_after,fit_stats=fit(parent,opt,inputs,targets,epochs=2,lr=.0002,seed=SEED)
    key=save_snapshot(model_dir,candidate,opt_after,{
        "parent":BASE,"purpose":"D58 fourth selfplay1000 direct D52 NNUE continuation",
        "new_games":1000,"resolved_new_games":len(resolved),
        "old_bootstrap_replay_games":665,"prior_d64_replay_games":300,
        "formal_search_variant":"d48_pvs_mate",
        "source_release_sha256":source_sha,
        "prior_model_release_sha256":games.D64_TRAIN_SHA,
        "old_replay_sha256":games.D64_SELFPLAY_SHA,
        "learning_rate":.0002,"epochs":2,"outcome_weight":.75,"td_lambda":.8,
        "training":fit_stats})
    if opt_after["step"]<=10974:raise ValueError("Adam did not advance")
    report={"schema":"d66-learned1000-v1","baseline":BASE,"trained_sha256":key,
        "optimizer_step_before":10974,"optimizer_step_after":opt_after["step"],
        "new_games":1000,"resolved_new_games":len(resolved),
        "old_bootstrap_replay_games":665,"prior_d64_replay_games":300,
        "samples":sample_stats,"fit":fit_stats,
        "source_sha256":source_sha,"formal_search_variant":"d48_pvs_mate",
        "strength_proven":False,"formal_model_changed":False}
    atomic_json(out/"report.json",report)
    published=out/"publication";published.mkdir(exist_ok=True)
    for name in (f"{key}.npz",f"{key}.json"):
        (published/name).write_bytes((model_dir/name).read_bytes())
    (published/"report.json").write_bytes((out/"report.json").read_bytes())
    artifact=out/"D66-D64-1000trained-unadopted.tar.gz"
    archive_tool.pack_tar(published,artifact)
    atomic_json(out/"receipt.json",{"sha256":digest(artifact.read_bytes()),
        "model_sha256":key,"source_sha256":source_sha,"optimizer_step_after":opt_after["step"]})
    print(json.dumps(report,ensure_ascii=False))

def main():
    p=argparse.ArgumentParser()
    for flag in ("state","baseline-trained","old-selfplay","source","out"):
        p.add_argument("--"+flag,type=Path,required=True)
    p.add_argument("--source-sha",required=True)
    x=p.parse_args()
    if len(x.source_sha)!=64:raise ValueError("source SHA256 required")
    train(x.state,x.baseline_trained,x.old_selfplay,x.source,x.source_sha,x.out)
if __name__=="__main__":main()
